#!/usr/bin/env python3
"""
emwidth.py — 글자 한 자의 폭(em) 어림. **그 어림의 집이 여기 하나다.**

── 왜 생겼나 (2026-10-11 · DECISIONS §472) ─────────────────────
같은 어림이 **두 자리에 서로 다른 수로** 있었다 —

    tools/svg_fit.py            넓은 글자 1.0 · 나머지 0.6   유니코드 **구간**으로 가른다
    src/firelane/vehiclecard.py 한글     1.0 · 나머지 0.55   `[가-힣]` 하나로 가른다

★ 둘째 것은 **원인이 §469 · §471 과 같다** — 정본이 `tools/` 에 있어
  `src/firelane` 이 import 할 수 없었다. 같은 자리에서 세 번째다. 그래서
  이번에는 **먼저 집을 `src` 로 올린다**(§471 이 세운 규약).

★ `svg_fit` 쪽은 **값이 한 글자도 안 바뀐다** — 여기 있는 함수가 그 파일에서
  옮겨 온 그것이다(구간 다섯 · 0.6). 그림 관문 전부로 실측했다.

★ `vehiclecard` 쪽은 **이 판에서 안 바꾼다.** 바꾸면 그 모듈의 코드 축이
  움직여 `vehicle_spec` norm 을 다시 구워야 하고, 원본 관리카드 PDF 는
  레이크에 있다 — **못 재는 것을 고치지 않는다**(PLAN #169 가 든다).

── 두 자리는 **다른 일감이다** ────────────────────────────────
`svg_fit` 은 「넘치는가」를 묻고 **넘치게 세는 쪽이 안전**하다(보수적 과대).
`vehiclecard` 는 머리글 칸의 **중심**을 찾으므로 과대도 과소도 틀린다.
그래서 두 수가 다른 것 자체는 결함이 아니다. 결함은 **구간을 안 보는 것**이다 —
`㎏`(U+33A5) · 한자 · 전각은 넓은 글자인데 `[가-힣]` 은 그것을 좁다고 센다.

IN    없음 (순수 함수)
OUT   없음
PARAM 없음
부류  몸통   진입점이 아니다 — 부르는 쪽이 부류를 든다  (DECISIONS §437)
밖    **글꼴을 안 본다.** 정확한 측정은 `PIL.ImageFont.getlength` 가 하고,
      이 저장소는 그것을 **일부러 안 쓴다** — 한 글꼴로 정확히 재면 그
      글꼴에서만 맞고 다른 기계에서 넘친다(DECISIONS §470 의 그 자리).
      자간·합자·세로쓰기도 안 본다.
"""
from __future__ import annotations

#: 넓은 글자(1.0em)로 세는 유니코드 구간. 한글 자모 · CJK · 한글 음절 ·
#: 호환 한자 · 전각 꼴이다. `㎏`(U+33A5)은 세 번째 구간 안이다.
WIDE_RANGES: tuple[tuple[int, int], ...] = (
    (0x1100, 0x11FF),   # 한글 자모
    (0x2E80, 0x9FFF),   # CJK 부수 ~ 한자 · 기호(㎏ · ℃ 포함)
    (0xAC00, 0xD7AF),   # 한글 음절
    (0xF900, 0xFAFF),   # CJK 호환 한자
    (0xFF00, 0xFF60),   # 전각 라틴 · 기호
)

#: 넓은 글자의 폭(em).
WIDE_EM = 1.0

#: 나머지의 폭(em). **공백도 이 값이다** — 보수적으로 센다.
NARROW_EM = 0.6


def em(ch: str) -> float:
    """글자 한 자의 폭(em). 넓은 글자 1.0 · 나머지 0.6 — **어림이다.**

    ★ 한 글자만 받는다. 문자열 전체 폭은 부르는 쪽이 더한다 — 그래야
      `text-anchor` 나 칸 중심처럼 **더한 뒤의 규칙**이 부르는 쪽에 남는다.
    """
    o = ord(ch)
    return WIDE_EM if any(lo <= o <= hi for lo, hi in WIDE_RANGES) else NARROW_EM
