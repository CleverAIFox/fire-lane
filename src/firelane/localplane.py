from __future__ import annotations

import math

#: 동명동 중심 위도. 근사의 기준점이다.
LAT0 = 35.151

#: 기준 경도. 상수를 **어디서 쟀는가**를 적어 둔다 — 안 적으면 다시 못 잰다.
LON0 = 126.9266

#: 경도 1도의 미터 — 그 기준점에서. `pyproj` 실측 91,120.151 을 정수로 끊었다.
#: **`111,320 × cos(위도)` 가 아니다** — 그 꼴은 회전타원체를 구로 보므로
#: 0.111% 작게 나온다(§473).
#:
#: ★ **밑줄을 안 쓴다** — `tests/test_sources_of_truth.py` 가 이 값을 글자로
#:   들고 `web/navi` 의 TS 표기(`91120`)와 대야 하기 때문이다(§473).
#: ★ **`float` 다. 정수로 적으면 조용히 틀린다** — `shapely.ops.transform` 은
#:   먼저 좌표를 **튜플로 묶어** 콜백에 넘긴다(`func(*zip(*coords))`). 거기서
#:   `튜플 * 정수` 는 곱이 아니라 **튜플 반복**이고, 그러면 변환이 안 된
#:   도형이 나오면서 메모리가 터진다. `float` 면 `TypeError` 가 나고 그쪽이
#:   스칼라 경로로 되돌려 **맞게** 돈다(§473-5). `tests/test_localplane.py`
#:   가 그 자리를 양방향으로 든다.
MX = 91120.0

#: 위도 1도의 미터 — 그 기준점에서. `pyproj` 실측 110,943.342 를 정수로 끊었다.
#: **110,574 가 아니다** — 그것은 **적도**의 자오선 1도다(§473).
#: **111,320 도 아니다** — 그것은 적도의 **경도** 1도다(§469).
#: ★ `MX` 와 같은 이유로 **`float` 다**(§473-5).
MY = 110943.0


def metres(a: tuple[float, float], b: tuple[float, float]) -> float:
    """4326 두 점 `(경도, 위도)` 사이 거리(m). 국소 평면 근사.

    ★ 받는 꼴이 **(경도, 위도)** 다 — GeoJSON 순서이고, 이 저장소의 그래프
      노드가 그 꼴로 산다. 뒤집어 넘기면 조용히 엉뚱한 수가 나오므로
      부르는 쪽이 그 순서를 지킨다(시험이 양쪽을 묶는다).
    """
    return math.hypot((a[0] - b[0]) * MX, (a[1] - b[1]) * MY)
