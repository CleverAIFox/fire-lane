#!/usr/bin/env python3
"""
localplane.py — 동명동 국소 평면 근사. **좌표 상수의 집이 여기 하나다.**

── 왜 또 옮겼나 (2026-10-11 · DECISIONS §469) ──────────────────
§239 가 같은 세 줄을 세 도구에서 걷어 `tools/localgeo.py` 로 올렸다. 그런데
그 뒤로 **같은 상수가 네 자리에 다시 섰고, 값이 서로 달랐다** —

    tools/localgeo.py            MY 110_574
    src/firelane/publish_context.py  110_540
    tools/navicheck.py           111_320   ← 위도에 경도 미터를 쓴다
    tools/desk_check.py          111_320   ← 같은 자리

위도 1도를 **세 수**로 재고 있었다. 판정이 안 뒤집히는 크기(0.67%)라
아무도 안 울었고, 그래서 §239 가 고친 2족이 **넉 달 만에 넷으로** 돌아왔다.

★ 집을 `src/firelane` 으로 올린다. `tools/localgeo.py` 에 두면 `src` 쪽이
  그것을 import 할 수 없다(계층) — 그래서 `publish_context` 가 제 상수를
  갖고 있었던 것이다. **정본을 못 쓰게 두면 사본이 생긴다.**

★ 봉인은 안 움직인다. 실측 — 봉인되는 폐포 셋(`firelane.segments` ·
  `firelane.ingest` · `firelane.ortho`)이 이 파일을 **하나도 안 든다.**
  `firelane.publish_web` 만 늘고 그쪽은 샤드 봉인 대상이 아니다.

★ `seg/params.py` 로는 **안 올린다** — 그 파일은 판정 지문 안이고, 이 값은
  판정에 안 든다(§239 가 적은 그대로다). 정본을 하나로 만드는 것과 지문을
  흔드는 것은 다른 일이다.

── 무엇이 아닌가 ───────────────────────────────────────────────
★ **투영이 아니다.** 제대로 된 변환은 EPSG:5186 이고 `pyproj` 가 한다.
  여기 있는 것은 **한 동네 크기에서만 성립하는 어림**이다.

IN    없음 (상수)
OUT   없음 (상수와 거리 함수)
PARAM 없음
부류  몸통   진입점이 아니다 — 부르는 쪽이 부류를 든다  (DECISIONS §437)
밖    **좌표계 변환은 안 한다.** 4326 두 점 사이 거리 하나를 든다.
      고도·측지선은 안 본다 — 평면 근사다.
"""
from __future__ import annotations

import math

#: 동명동 중심 위도. 근사의 기준점이다.
LAT0 = 35.151

#: 경도 1도의 미터 — 그 위도에서. 적도 111,320m 에 `cos(위도)` 를 곱한다.
MX = 111_320 * math.cos(math.radians(LAT0))

#: 위도 1도의 미터. **111,320 이 아니다** — 그것은 적도의 경도 1도다.
#: 자오선 쪽은 이 위도에서 110,574m 이고, 섞으면 0.67% 틀린다(§469).
MY = 110_574


def metres(a: tuple[float, float], b: tuple[float, float]) -> float:
    """4326 두 점 `(경도, 위도)` 사이 거리(m). 국소 평면 근사.

    ★ 받는 꼴이 **(경도, 위도)** 다 — GeoJSON 순서이고, 이 저장소의 그래프
      노드가 그 꼴로 산다. 뒤집어 넘기면 조용히 엉뚱한 수가 나오므로
      부르는 쪽이 그 순서를 지킨다(시험이 양쪽을 묶는다).
    """
    return math.hypot((a[0] - b[0]) * MX, (a[1] - b[1]) * MY)
