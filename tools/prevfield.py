#!/usr/bin/env python3
"""
prevfield.py — **유병률 칸의 문법.** 이 칸이 무엇을 요구하는가만 든다.

**진입점이 아니다.** `tools/dms.py::prevalence` 가 부르고 판정을 찍는다 —
프로브(합성 결함을 양쪽으로 미는 자리)도 그쪽 `--selftest` 하나다. 두 벌을
두면 갈린다(2족).

── 왜 갈라 나왔나 (2026-10-13 · DECISIONS §511-2) ──────────────
근거 방향 그물을 `dms.py` 안에 넣자 그 파일이 **1,863줄**이 됐고 `sizecheck`
가 울었다(예외 1,761). 예외를 1,863으로 올리는 것은 **신호를 끄는 쪽**이고,
§440 이 그 족에 유병률 **7회**를 적어 뒀다 — 「상한에 붙어 사는 파일을
쪼갠다 — 예외를 올려 신호를 끄지 않는다」. 그래서 쪼갰다.

★ 자른 자리는 **순수한 쪽**이다. 절을 훑고 칸을 떠내는 일(`sections` ·
  `field_block`)은 여러 칸이 같이 쓰므로 `dms.py` 에 남는다. 여기는 **떠낸
  글 한 덩이**를 받아 옳은지만 본다 — 그래서 이 파일은 `dms` 를 안 부르고,
  거꾸로 불린다. 둘이 서로를 부르면 순환이다.

부류  몸통   진입점이 **아니다.** 부류는 부르는 쪽에서 물려받는다  (DECISIONS §398)

IN    (절 번호, 유병률 칸의 글) — 부르는 쪽이 떠서 넘긴다
OUT   `prev_cites()` · `fwd_defect()` · `ratchet_defect()` (부르는 쪽이 찍는다)
PARAM PREV_FROM · KNOWN_FWD · FWD_MAX
밖    **횟수가 맞는가는 안 본다.** 「2회」가 실제로 두 번인지는 사람이 안다.
      여기가 드는 것은 ① 적었나 ② 수를 읽을 수 있나 ③ **근거가 앞을
      가리키나** 셋이다. ③ 만이 옳고 그름이고, 그것이 가능한 이유는
      유병률이 **역사**라서다. 칸을 떠내는 일은 `dms.py` 소관이다.
"""
from __future__ import annotations

import re

# ── 유병률 칸 ──────────────────────────────────────────────────
# ★ 2026-10-06 (DECISIONS §405 · PLAN #150). 관문을 세우는 절이 **그 관문이 막는
#   병이 몇 번 났는지**를 안 적었다. 안 적으면 그 관문은 **영원히 못 지운다** —
#   지웠을 때 무엇이 터질지 아무도 모르기 때문이다. 0 이면 0 이라고 적는다.
#   **0 이라고 적힌 관문이 나중에 지울 수 있는 관문**이다.
#
# ★ 새로 만든 어휘가 아니다. §390 · §391 · §392 가 2026-10-04 에 손으로 적었고
#   그 뒤 열한 절이 안 적었다 — 사람이 기억으로 지키던 규약이다(§390 이 배운 것과
#   같은 자리: 「규약을 되풀이하는 것은 강제자가 아니다」).
PREV = re.compile(r"^\s{0,6}(?:[-*>]\s*)?\*{0,2}유병률\*{0,2}(?![가-힣(])")
#: 그 칸이 적은 **횟수**. `**2회**` · `0 회` · `두 번` 을 다 받는다.
PREV_N = re.compile(r"\*{0,2}\s*(?:([0-9]+)|(한|하나|두|둘|세|셋|네|넷|다섯|여섯|"
                    r"일곱|여덟|아홉|열))\s*\*{0,2}\s*(?:회|번)")
#: **소급하지 않는다.** 이 번호부터 요구한다 — 405절을 소급해 지어내면 그것이
#: 거짓 기록이다(`tests/test_defect_evidence.py` 가 §217 하한에 쓴 것과 같은 사유).
PREV_FROM = 405

# ── 근거가 가리키는 **방향** ────────────────────────────────────
# ★ 2026-10-13 (DECISIONS §511). `dms.py::prevalence` 의 머리말이 「수의 옳고
#   그름은 기계가 못 본다 — 사람이 적고, 기계는 **빈 자리**를 센다」고 적었다.
#   그 주장이 **너무 넓었다.** 한 가지는 기계가 본다:
#
#       유병률은 **역사**다. 그래서 근거는 **자기보다 앞**에 있어야 한다.
#
#   뒤를 가리키면 그 사례는 아직 없었던 것이고, 적힌 횟수가 실수보다 하나
#   크다. 그 수가 관문을 세울지 말지를 가르므로(§405), 하나 큰 수는 **없어도
#   될 관문을 세우는 쪽**으로 틀린다. 사유는 DECISIONS §511 이 든다.
#: 근거 괄호가 **자기보다 뒤**를 가리키는 것이 기록된 자리. §507-1(「왜 지우지
#: 않고 **적는가**」)을 그대로 따른다 — 거짓 칸을 고쳐 지우면 그 절이 무엇을
#: 틀렸는지가 사라지고, 같은 실수를 또 한다.
KNOWN_FWD = {
    508: "§511-1 이 정정했다 — 진짜 둘째는 §218-7 ① 이고 유병률은 3 이다",
}
#: ★ 예외는 **늘 수 없다.** `tools/mergecheck.py` 의 `BYPASS_MAX` 와 같은 꼴 —
#:   중앙 래칫(`tools/ratchet.py`)이 이 도구를 안 보므로 도구가 제 상한을 든다.
#:   「예외는 늘 자리가 아니다」. 줄이려면 그 절에 정정을 달고 여기서 뺀다.
FWD_MAX = 1
#: 「족」을 닫는 `」` 와 근거 괄호 `(` 사이에 **산문이 끼면 근거가 아니다** —
#: 뒤에 덧붙인 보강이다(§440 의 `§445-1` 이 그 자리다). 별표와 줄표만 허용한다.
_GAP = re.compile(r"^[\s*—\-·]*$")


def prev_cites(blk: str) -> list[int]:
    """유병률 칸이 **근거로 든** 절 번호. 「족」 바로 뒤의 괄호 하나만 본다.

    ★ 괄호 **밖**은 안 본다. 그 자리는 뒤에 덧붙인 보강이고(§440 의
      `§445-1`), 보강은 나중에 쓰므로 뒤를 가리키는 것이 정상이다. 괄호
      안쪽만 보면 106칸 중 걸리는 것이 **하나**다 — 거짓 양성이 없다.
    ★ 괄호를 **균형으로** 닫는다. `(§431 · PLAN #159(닫힘) 의 …)` 처럼 안에
      괄호가 또 있어서, 첫 `)` 에서 끊으면 근거를 반만 읽는다.
    """
    out: list[int] = []
    for m in re.finditer("」", blk):
        i = blk.find("(", m.end())
        if i < 0 or not _GAP.match(blk[m.end():i]):
            continue
        depth = 0
        for j in range(i, len(blk)):
            depth += (blk[j] == "(") - (blk[j] == ")")
            if depth == 0:
                out += [int(x) for x in re.findall(r"§(\d+)", blk[i:j + 1])]
                break
    return out


def fwd_defect(num: int, blk: str) -> str | None:
    """§`num` 의 유병률 근거가 **자기보다 뒤**를 가리키는가. 순수하다."""
    fwd = sorted({c for c in prev_cites(blk) if c > num})
    if not fwd or num in KNOWN_FWD:
        return None
    return (f"근거가 **자기보다 뒤**를 가리킨다 — "
            f"§{' · §'.join(str(c) for c in fwd)}. 유병률은 역사라 그 사례는 "
            f"아직 없었다. 적힌 수가 하나 크다")


def ratchet_defect() -> str | None:
    """적힌 예외가 **늘었는가.** 늘면 그것은 느슨해지는 쪽이다."""
    if len(KNOWN_FWD) <= FWD_MAX:
        return None
    return (f"  tools/prevfield.py  `KNOWN_FWD` 가 {len(KNOWN_FWD)} — 래칫 "
            f"{FWD_MAX} 보다 늘었다. **예외는 늘 자리가 아니다**")


def selftest() -> list[str]:
    """합성 결함을 **양쪽으로** 민다. 한 방향만 밀면 「언제나 통과」와
    「언제나 빨강」을 못 가른다(§405 가 이 칸에 쓴 규율 그대로).

    ★ 부르는 쪽은 `dms.py --selftest` 하나다. 여기에 **제 진입점**을 두면
      프로브가 두 벌이 되고 둘이 갈린다 — `tools/toolclass.py` 가 그 글자를
      보고 부류를 도출하므로, 금칙을 적을 때도 그 글자를 안 쓴다.
    """
    bad: list[str] = []
    n = PREV_FROM + 90                      # `KNOWN_FWD` 에 없는 번호여야 한다
    if n in KNOWN_FWD:
        bad.append("프로브 번호가 예외 목록과 겹친다 — 그물이 비었다")
    if not fwd_defect(n, f"유병률  **2회** — 「족」(§{n + 1} · 이 절)"):
        bad.append("근거가 자기보다 뒤를 가리키는 것을 통과시킨다 — "
                   "유병률은 역사라 그 사례는 아직 없었다")
    if fwd_defect(n, f"유병률  **2회** — 「족」(§{n - 1} · 이 절)"):
        bad.append("앞을 가리키는 정상 근거를 잡는다 — 언제나 빨강이다")
    # ★ 괄호 **밖**의 뒤 참조는 보강이다(§440 의 `§445-1`). 잡으면 안 된다
    if fwd_defect(n, f"유병률  **2회** — 「족」(§{n - 1} · 이 절). "
                     f"**같은 물음이고 §{n + 1} 이 묶었다**"):
        bad.append("근거 괄호 밖의 보강을 근거로 읽는다 — 보강은 뒤에 쓴다")
    # ★ 안에 괄호가 또 있으면 **균형으로** 닫는다. 첫 `)` 에서 끊으면 반만 읽는다
    if not fwd_defect(n, f"유병률  **2회** — 「족」(§{n - 1} · "
                         f"PLAN #9(닫힘) 의 지문 · §{n + 1})"):
        bad.append("중첩 괄호에서 뒤쪽 근거를 못 읽는다 — 첫 닫는 괄호에서 끊었다")
    # ★ 예외로 **적힌** 자리는 안 울린다 — 지우지 않고 적는다(§507-1)
    k = next(iter(KNOWN_FWD))
    if fwd_defect(k, f"유병률  **2회** — 「족」(§{k + 1} · 이 절)"):
        bad.append(f"§{k} 가 `KNOWN_FWD` 에 적혀 있는데도 울린다")
    # ★ 래칫 — **늘면 운다.** 사전이므로 제자리에서 늘리고 바로 뺀다
    if ratchet_defect():
        bad.append("예외가 안 늘었는데 래칫이 운다 — 언제나 빨강이다")
    probe = 10**6
    KNOWN_FWD[probe] = "합성 — selftest 가 넣고 바로 뺀다"
    try:
        if not ratchet_defect():
            bad.append("`KNOWN_FWD` 가 늘어도 안 운다 — 래칫이 제 바닥에 앉았다")
    finally:
        KNOWN_FWD.pop(probe, None)
    return bad
