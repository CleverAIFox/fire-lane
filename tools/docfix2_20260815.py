def apply(rel: str, pairs, check: bool) -> int:
    path = ROOT / rel
    text = path.read_text(encoding="utf-8")
    fail = 0
    for i, (old, new) in enumerate(pairs, 1):
        n = text.count(old)
        if n != 1:
            print(f"! {rel} #{i} 앵커 {n}회 — {old.splitlines()[0][:55]}")
            fail += 1
            continue
        text = text.replace(old, new, 1)
    if not check and not fail:
        path.write_text(text, encoding="utf-8")
        print(f"  {rel} {len(pairs)}건")
    return fail


def main() -> int:
    check = "--check" in sys.argv
    fail = apply("docs/MASTER.md", PAIRS_MASTER, check)
    fail += apply("docs/PLAN.md", PAIRS_PLAN, check)
    print("\n" + ("★ 앵커 %d 건 실패. 쓰지 않았다." % fail if fail
                  else "앵커 전건 일치." + ("" if check else " 적용 완료.")))
    return 1 if fail else 0


if __name__ == "__main__":
    sys.exit(main())
