def main() -> int:
    check = "--check" in sys.argv
    fail = 0
    for path, pairs in TARGETS:
        text = path.read_text(encoding="utf-8")
        for i, (old, new) in enumerate(pairs, 1):
            n = text.count(old)
            if n != 1:
                print(f"! {path.name} #{i} 앵커 {n}회 — {old.splitlines()[0][:60]}")
                fail += 1
                continue
            text = text.replace(old, new, 1)
        if not check and not fail:
            path.write_text(text, encoding="utf-8")
            print(f"  {path.relative_to(ROOT)} {len(pairs)}건 적용")
    if fail:
        print(f"\n★ 앵커 {fail}건 실패. 아무것도 쓰지 않았다.")
        return 1
    print("\n앵커 전건 일치." + ("" if check else " 적용 완료."))
    return 0


if __name__ == "__main__":
    sys.exit(main())
